#!/usr/bin/env node
// Generates docs/status.md from run records and the ledger, so counts in prose cannot drift.
// The output has no timestamp: it changes only when the records or the ledger change,
// and `npm run check` rejects a stale copy.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { summarize } from './compare.mjs';
import { readRun } from './lib/records.mjs';
import { main } from './lib/cli.mjs';

const STATUSES = ['planned', 'prepared', 'running', 'awaiting_review', 'aborted', 'completed'];
const VERDICTS = ['pass', 'fail', 'partial'];
const count = (items, predicate) => items.filter(predicate).length;
const table = (head, rows) => [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map(row => `| ${row.join(' | ')} |`)];

export function ledgerStatuses(text) {
  const totals = {};
  for (const line of text.split('\n')) {
    if (!/^\| L\d/.test(line)) continue;
    const status = line.split('|').at(-2).trim();
    totals[status] = (totals[status] ?? 0) + 1;
  }
  return totals;
}

/** Pure rendering: `records` are run.json objects, `report` is the summarize() result from compare. */
export function renderStatus(records, report, ledgerText) {
  const executed = records.filter(r => r.execution?.started_at);
  const evaluated = records.filter(r => r.status === 'completed');
  const finished = executed.map(r => r.execution.finished_at).filter(Boolean).sort().at(-1);
  const verdicts = VERDICTS.map(v => `${v} ${count(evaluated, r => r.verdict?.result === v)}`).join(', ');
  const triples = report.groups.flatMap(g => g.harnesses).reduce((sum, h) => sum + h.triples.length, 0);
  const crossHarness = count(report.groups, g => g.harnesses.length > 1);
  const ledger = ledgerStatuses(ledgerText);
  const ledgerRows = Object.values(ledger).reduce((a, b) => a + b, 0);
  const ledgerParts = Object.entries(ledger).sort().map(([status, n]) => `${n} ${status}`).join(', ');

  const cells = new Map();
  for (const record of records) {
    const key = [record.harness?.name ?? 'not set', record.task ?? 'not set', record.model?.provider ?? 'not set', record.model?.id ?? 'not set'];
    const id = JSON.stringify(key);
    if (!cells.has(id)) cells.set(id, { key, records: [] });
    cells.get(id).records.push(record);
  }
  const rows = [...cells.keys()].sort().map(id => {
    const { key, records: group } = cells.get(id);
    return [...key.map(value => `\`${value}\``),
      ...STATUSES.map(status => count(group, r => r.status === status)),
      ...VERDICTS.map(verdict => count(group, r => r.status === 'completed' && r.verdict?.result === verdict))];
  });
  const waiting = records.filter(r => r.status === 'awaiting_review').map(r => r.run_id).sort();

  return [
    '# Lab status',
    '',
    'Generated by `node scripts/status.mjs --write` from `results/runs/*/run.json` and `docs/harness-ledger.md`. Do not edit by hand: `npm run check` fails when this page is stale. These counts are our records, not claims about agent quality; see `npm run compare` for conditions.',
    '',
    '## Summary',
    '',
    `- Run records: ${records.length}.`,
    `- Agent executions started: ${executed.length}${finished ? `; the latest finished on ${finished.slice(0, 10)}` : ''}.`,
    `- Independently evaluated: ${evaluated.length} (${verdicts}).`,
    `- Complete triples under matching conditions: ${triples}.`,
    `- Condition groups with more than one harness: ${crossHarness}.`,
    `- Ledger rows: ${ledgerRows} (${ledgerParts}).`,
    '',
    '## Records by harness, task and model',
    '',
    ...table(['Harness', 'Task', 'Provider', 'Model', ...STATUSES.map(s => `\`${s}\``), ...VERDICTS], rows),
    '',
    '## Awaiting independent evaluation',
    '',
    ...(waiting.length ? waiting.map(id => `- \`${id}\``) : ['None.']),
    '',
  ].join('\n');
}

export function statusFor(root) {
  const dir = join(root, 'results/runs');
  const records = readdirSync(dir).filter(id => /^\d{4}-/.test(id)).map(id => readRun(root, id));
  return renderStatus(records, summarize(root), readFileSync(join(root, 'docs/harness-ledger.md'), 'utf8'));
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await main(() => {
  const root = process.cwd(), flags = process.argv.slice(2);
  if (flags.some(flag => flag !== '--write')) throw new Error('Usage: status.mjs [--write]');
  const text = statusFor(root);
  if (flags.length) { writeFileSync(join(root, 'docs/status.md'), text); console.log('[status] docs/status.md written'); }
  else process.stdout.write(text);
});
