"""Local negative controls for the synthetic verifier; no model or container calls."""

import importlib.util
import json
import sys
import tempfile
import unittest
from pathlib import Path

TASK = Path(__file__).parent / "task"
sys.dont_write_bytecode = True
SPEC = importlib.util.spec_from_file_location("synthetic_evaluator", TASK / "tests/evaluate.py")
EVALUATOR = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(EVALUATOR)


class SyntheticVerifierTests(unittest.TestCase):
    def test_generated_bytecode_does_not_change_harbor_checksum(self):
        from harbor.models.task.task import Task

        before = Task(TASK).checksum
        cache = TASK / "tests/__pycache__"
        cache.mkdir(exist_ok=True)
        try:
            with tempfile.NamedTemporaryFile(dir=cache, suffix=".pyc") as generated:
                generated.write(b"synthetic generated bytecode control")
                generated.flush()
                self.assertEqual(Task(TASK).checksum, before)
        finally:
            if not any(cache.iterdir()):
                cache.rmdir()

    def test_artifact_controls(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "result.json"
            fixture = TASK / "tests/expected.json"
            cases = [
                (None, 0),
                ("not json", 0),
                (json.dumps(["pear", "banana", "apple"]), 0),
                (json.dumps(["apple", "banana", "pear", "pear"]), 0),
                (fixture.read_text(), 1),
                (fixture.read_text() + " " * 1024, 0),
            ]
            for payload, expected in cases:
                with self.subTest(payload=payload):
                    if payload is not None:
                        output.write_text(payload)
                    self.assertEqual(EVALUATOR.evaluate(output, fixture)[0], expected)
            output.unlink()
            output.symlink_to(fixture.resolve())
            self.assertEqual(EVALUATOR.evaluate(output, fixture)[0], 0)


if __name__ == "__main__":
    unittest.main()
